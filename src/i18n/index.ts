const getDefaultLocale = (): AppLocale => {
  try {
    const stored = localStorage.getItem('app-settings')
    if (stored) {
      const parsed = JSON.parse(stored)
      if (parsed.language === 'zh-CN' || parsed.language === 'en-US') {
        return parsed.language
      }
    }
  } catch {
    // Ignore invalid persisted settings and fall back to browser language.
  }

  const browserLanguage =
    navigator.language ||
    (navigator as Navigator & { userLanguage?: string }).userLanguage ||
    ''

  return browserLanguage.toLowerCase().includes('zh') ? 'zh-CN' : 'en-US'
}

const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: getDefaultLocale(),
  fallbackLocale: 'en-US',
  messages,
})

export default i18n
